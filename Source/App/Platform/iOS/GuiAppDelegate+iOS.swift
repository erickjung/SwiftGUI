#if os(iOS)

import Foundation
import UIKit

/// iOS-specific app delegate that manages the application lifecycle.
///
/// This type is created automatically by the app layer and is not part
/// of the public API.
internal class GuiAppDelegateiOS: UIResponder, UIApplicationDelegate {
    var window: UIWindow?

    func application(
        _ application: UIApplication,
        didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?
    ) -> Bool {
        return true
    }

    func application(
        _ application: UIApplication,
        configurationForConnecting connectingSceneSession: UISceneSession,
        options: UIScene.ConnectionOptions
    ) -> UISceneConfiguration {
        let config = UISceneConfiguration(
            name: "Default Configuration",
            sessionRole: connectingSceneSession.role
        )
        config.delegateClass = GuiSceneDelegateiOS.self
        return config
    }
}

#endif
